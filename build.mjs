// Bundles src/main.ts + @humanauth/verifier + jose + canonicalize into one
// readable ESM file at scripts/phone-approval.mjs. The bundle is committed:
// a Claude Code plugin is cloned, not installed, so the hook must run with
// nothing but Node on PATH.
//
//   node build.mjs           write the bundle
//   node build.mjs --check   fail if the committed bundle is stale (CI)

import { build } from "esbuild";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";

const OUT = new URL("./scripts/phone-approval.mjs", import.meta.url);
mkdirSync(new URL("./scripts/", import.meta.url), { recursive: true });
const check = process.argv.includes("--check");

const result = await build({
  entryPoints: [new URL("./src/main.ts", import.meta.url).pathname],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  write: false,
  minify: false,
  legalComments: "none",
  banner: {
    js: [
      "#!/usr/bin/env node",
      "// humanauth Claude Code plugin — PreToolUse hook.",
      "// Generated by build.mjs from src/; do not edit. Source: https://github.com/humanauth-ai/humanauth-plugin",
      // jose and canonicalize are CJS-compatible; give them a `require`.
      "import { createRequire as __createRequire } from 'node:module';",
      "const require = __createRequire(import.meta.url);",
    ].join("\n"),
  },
});

const code = result.outputFiles[0].text;

if (check) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== code) {
    console.error("scripts/phone-approval.mjs is stale: run `npm run build` and commit the result");
    process.exit(1);
  }
  console.log("bundle is up to date");
} else {
  writeFileSync(OUT, code);
  console.log(`wrote ${OUT.pathname} (${(code.length / 1024).toFixed(0)} KB)`);
}
